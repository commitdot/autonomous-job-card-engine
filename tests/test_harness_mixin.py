class TestHarnessCandidate(unittest.TestCase):
    def test_default_status_pending(self):
        c = HarnessCandidate()
        self.assertEqual(c.status, "pending")
        self.assertEqual(c.score, 0.0)
        self.assertIsInstance(c.harness, HarnessConfig)

    def test_candidate_id_autogenerated(self):
        c1 = HarnessCandidate()
        c2 = HarnessCandidate()
        self.assertTrue(c1.candidate_id.startswith("hc-"))
        self.assertNotEqual(c1.candidate_id, c2.candidate_id)

    def test_to_dict_from_dict_round_trip(self):
        c = HarnessCandidate(
            harness=HarnessConfig(system_prompt="Test.", guardrails=["G1"]),
            status="success",
            score=0.9,
            stdout="OK",
        )
        d = c.to_dict()
        self.assertIn("harness", d)
        self.assertEqual(d["status"], "success")
        self.assertEqual(d["score"], 0.9)

        restored = HarnessCandidate.from_dict(d)
        self.assertEqual(restored.status, "success")
        self.assertEqual(restored.score, 0.9)
        self.assertEqual(restored.harness.system_prompt, "Test.")
        self.assertEqual(restored.harness.guardrails, ["G1"])


