class TestSimAdapterPropose(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.adapter = SimAdapter(workspace_root=self.tmp)
        self.deliverables = [{"path": "out/result.py", "description": "Result module"}]
        self.objective = "Write a Python function that adds two numbers."

    def test_returns_requested_count(self):
        candidates = self.adapter.propose_harness_candidates(
            self.objective, self.deliverables, n_candidates=3
        )
        self.assertEqual(len(candidates), 3)

    def test_returns_one_candidate(self):
        candidates = self.adapter.propose_harness_candidates(
            self.objective, self.deliverables, n_candidates=1
        )
        self.assertEqual(len(candidates), 1)

    def test_all_candidates_pending(self):
        candidates = self.adapter.propose_harness_candidates(
            self.objective, self.deliverables, n_candidates=3
        )
        for c in candidates:
            self.assertEqual(c.status, "pending")

    def test_candidate_0_minimal(self):
        candidates = self.adapter.propose_harness_candidates(
            self.objective, self.deliverables, n_candidates=3
        )
        c0 = candidates[0]
        self.assertTrue(c0.harness.system_prompt)
        self.assertEqual(c0.harness.guardrails, [])

    def test_candidate_1_has_guardrails(self):
        candidates = self.adapter.propose_harness_candidates(
            self.objective, self.deliverables, n_candidates=3
        )
        c1 = candidates[1]
        self.assertGreater(len(c1.harness.guardrails), 0)
        self.assertGreater(len(c1.harness.memory), 0)

    def test_candidate_2_has_skills_and_tool_guidance(self):
        candidates = self.adapter.propose_harness_candidates(
            self.objective, self.deliverables, n_candidates=3
        )
        c2 = candidates[2]
        self.assertGreater(len(c2.harness.skills), 0)
        self.assertGreater(len(c2.harness.tool_guidance), 0)

    def test_context_lessons_injected_into_candidate_1(self):
        context = {"lessons": ["Use typing module.", "Prefer pathlib over os.path."]}
        candidates = self.adapter.propose_harness_candidates(
            self.objective, self.deliverables, n_candidates=2, context=context
        )
        c1 = candidates[1]
        self.assertTrue(any("Use typing" in g for g in c1.harness.guardrails))

    def test_all_candidates_are_harness_candidates(self):
        candidates = self.adapter.propose_harness_candidates(
            self.objective, self.deliverables, n_candidates=4
        )
        for c in candidates:
            self.assertIsInstance(c, HarnessCandidate)
            self.assertIsInstance(c.harness, HarnessConfig)

    def test_unique_candidate_ids(self):
        candidates = self.adapter.propose_harness_candidates(
            self.objective, self.deliverables, n_candidates=5
        )
        ids = [c.candidate_id for c in candidates]
        self.assertEqual(len(ids), len(set(ids)))


