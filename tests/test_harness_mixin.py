class TestSimAdapterCompose(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.adapter = SimAdapter(workspace_root=self.tmp)
        self.deliverables = [{"path": "comp.py", "description": "Composition output"}]
        self.objective = "Create a helper module."

    def _full_ppc(self, n_candidates: int = 3) -> "tuple[list, ComposedHarness]":
        """Run the full Propose→Probe→Compose pipeline and return (candidates, result)."""
        candidates = self.adapter.propose_harness_candidates(
            self.objective, self.deliverables, n_candidates=n_candidates
        )
        for i, c in enumerate(candidates):
            self.adapter.probe_execution(
                c, self.objective, self.deliverables,
                execution_root=self.tmp
            )
        result = self.adapter.compose_harness(candidates, self.objective, self.deliverables)
        return candidates, result

    def test_compose_returns_composed_harness(self):
        _, result = self._full_ppc(3)
        self.assertIsInstance(result, ComposedHarness)

    def test_compose_selects_a_winner(self):
        _, result = self._full_ppc(3)
        self.assertIsNotNone(result.winning_candidate_id)

    def test_compose_winner_id_is_in_candidates(self):
        candidates, result = self._full_ppc(3)
        ids = [c.candidate_id for c in candidates]
        self.assertIn(result.winning_candidate_id, ids)

    def test_compose_score_positive_when_any_pass(self):
        _, result = self._full_ppc(3)
        self.assertGreater(result.score, 0.0)

    def test_compose_candidates_evaluated_count(self):
        candidates, result = self._full_ppc(3)
        self.assertEqual(result.candidates_evaluated, 3)

    def test_compose_rationale_is_nonempty(self):
        _, result = self._full_ppc(3)
        self.assertGreater(len(result.synthesis_rationale), 0)

    def test_compose_deliverables_nonempty_on_success(self):
        _, result = self._full_ppc(3)
        self.assertGreater(len(result.deliverables), 0)

    def test_compose_empty_candidates_returns_no_winner(self):
        result = self.adapter.compose_harness([], self.objective, self.deliverables)
        self.assertIsNone(result.winning_candidate_id)
        self.assertEqual(result.score, 0.0)

    def test_compose_all_failed_returns_zero_score(self):
        candidates = self.adapter.propose_harness_candidates(
            self.objective, self.deliverables, n_candidates=1
        )
        # Minimal candidate (no guardrails, no skills) → probe sets status="failed", score=0.0
        self.adapter.probe_execution(
            candidates[0], self.objective, self.deliverables, execution_root=self.tmp
        )
        result = self.adapter.compose_harness(candidates, self.objective, self.deliverables)
        # _select_best_candidate picks the highest-scored probed candidate; since the
        # only candidate failed, its score is 0.0 and so is the composed result.
        self.assertEqual(result.score, 0.0)

    def test_compose_winner_has_highest_score(self):
        candidates, result = self._full_ppc(3)
        probed = [c for c in candidates if c.status != "pending"]
        best_score = max(c.score for c in probed)
        self.assertAlmostEqual(result.score, best_score)

    def test_compose_harness_config_matches_winner(self):
        candidates, result = self._full_ppc(3)
        winner = next(c for c in candidates if c.candidate_id == result.winning_candidate_id)
        self.assertEqual(result.harness.system_prompt, winner.harness.system_prompt)


