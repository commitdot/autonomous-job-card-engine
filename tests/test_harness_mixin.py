class TestHarnessMixinHelpers(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.adapter = SimAdapter(workspace_root=self.tmp)

    def _make_candidate(self, status: str, score: float, n_faults: int = 0) -> HarnessCandidate:
        c = HarnessCandidate(harness=HarnessConfig(system_prompt="X"))
        c.status = status
        c.score = score
        c.fault_frames = [{"line": "L1"}] * n_faults
        return c

    def test_score_candidate_success_no_faults(self):
        c = self._make_candidate("success", 0.0)
        score = self.adapter._score_candidate(c)
        self.assertAlmostEqual(score, 1.0)

    def test_score_candidate_success_with_faults(self):
        c = self._make_candidate("success", 0.0, n_faults=3)
        score = self.adapter._score_candidate(c)
        # 3 faults → penalty 0.3 → score 0.7
        self.assertAlmostEqual(score, 0.7)

    def test_score_candidate_failure(self):
        c = self._make_candidate("failed", 0.0)
        self.assertAlmostEqual(self.adapter._score_candidate(c), 0.0)

    def test_select_best_candidate_picks_highest_score(self):
        c1 = self._make_candidate("success", 0.6)
        c2 = self._make_candidate("success", 0.9)
        c3 = self._make_candidate("failed", 0.0)
        best = self.adapter._select_best_candidate([c1, c2, c3])
        self.assertIs(best, c2)

    def test_select_best_candidate_all_pending_returns_none(self):
        c1 = HarnessCandidate()
        c2 = HarnessCandidate()
        self.assertIsNone(self.adapter._select_best_candidate([c1, c2]))

    def test_select_best_candidate_empty_returns_none(self):
        self.assertIsNone(self.adapter._select_best_candidate([]))

    def test_build_contrast_rationale_includes_counts(self):
        c1 = self._make_candidate("success", 1.0)
        c2 = self._make_candidate("failed", 0.0)
        rationale = self.adapter._build_contrast_rationale([c1, c2], c1)
        self.assertIn("2 candidate", rationale)
        self.assertIn("1 passed", rationale)
        self.assertIn("1 failed", rationale)
        self.assertIn(c1.candidate_id, rationale)


