class TestHarnessConfig(unittest.TestCase):
    def test_default_fields(self):
        cfg = HarnessConfig()
        self.assertEqual(cfg.system_prompt, "")
        self.assertEqual(cfg.guardrails, [])
        self.assertEqual(cfg.memory, [])
        self.assertEqual(cfg.tool_guidance, [])
        self.assertEqual(cfg.subagents, [])
        self.assertEqual(cfg.skills, [])
        self.assertEqual(cfg.scripts, [])
        self.assertEqual(cfg.plugins, [])
        self.assertEqual(cfg.metadata, {})

    def test_to_dict_round_trip(self):
        cfg = HarnessConfig(
            system_prompt="Be helpful.",
            guardrails=["rule1", "rule2"],
            memory=["ctx1"],
            tool_guidance=["use pytest"],
            skills=["python"],
        )
        d = cfg.to_dict()
        restored = HarnessConfig.from_dict(d)
        self.assertEqual(restored.system_prompt, "Be helpful.")
        self.assertEqual(restored.guardrails, ["rule1", "rule2"])
        self.assertEqual(restored.memory, ["ctx1"])
        self.assertEqual(restored.skills, ["python"])

    def test_from_dict_ignores_extra_keys(self):
        d = {"system_prompt": "Hi", "nonexistent_key": "value"}
        cfg = HarnessConfig.from_dict(d)
        self.assertEqual(cfg.system_prompt, "Hi")
        self.assertFalse(hasattr(cfg, "nonexistent_key"))

    def test_render_prompt_block_empty(self):
        cfg = HarnessConfig()
        block = cfg.render_prompt_block()
        self.assertEqual(block, "")

    def test_render_prompt_block_system_prompt_only(self):
        cfg = HarnessConfig(system_prompt="You are an expert.")
        block = cfg.render_prompt_block()
        self.assertIn("## System Prompt", block)
        self.assertIn("You are an expert.", block)

    def test_render_prompt_block_all_components(self):
        cfg = HarnessConfig(
            system_prompt="Role.",
            guardrails=["G1"],
            memory=["M1"],
            tool_guidance=["T1"],
            subagents=["S1"],
            skills=["SK1"],
            scripts=["print('hello')"],
            plugins=["P1"],
        )
        block = cfg.render_prompt_block()
        for header in [
            "## System Prompt",
            "## Guardrails",
            "## Context Memory",
            "## Tool Guidance",
            "## Subagent Delegation",
            "## Active Skills",
            "## Injected Scripts",
            "## Plugin Directives",
        ]:
            self.assertIn(header, block, f"Missing section: {header}")

    def test_render_prompt_block_only_nonempty_sections(self):
        cfg = HarnessConfig(guardrails=["No hardcoded secrets."])
        block = cfg.render_prompt_block()
        self.assertIn("Guardrails", block)
        self.assertNotIn("System Prompt", block)
        self.assertNotIn("Context Memory", block)


