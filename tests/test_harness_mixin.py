class TestSimAdapterProbe(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.adapter = SimAdapter(workspace_root=self.tmp)
        self.deliverables = [{"path": "probe_out.py", "description": "Probe output"}]
        self.objective = "Implement a utility function."

    def _make_candidate(self, with_guardrails: bool = True) -> HarnessCandidate:
        cfg = HarnessConfig(system_prompt="Test agent.")
        if with_guardrails:
            cfg.guardrails = ["No breaking changes."]
        return HarnessCandidate(harness=cfg)

    def test_probe_with_guardrails_succeeds(self):
        c = self._make_candidate(with_guardrails=True)
        result = self.adapter.probe_execution(c, self.objective, self.deliverables)
        self.assertEqual(result.status, "success")
        self.assertGreater(result.score, 0.0)

    def test_probe_without_guardrails_fails(self):
        c = self._make_candidate(with_guardrails=False)
        result = self.adapter.probe_execution(c, self.objective, self.deliverables)
        self.assertEqual(result.status, "failed")
        self.assertEqual(result.score, 0.0)

    def test_probe_writes_file_to_execution_root(self):
        c = self._make_candidate(with_guardrails=True)
        result = self.adapter.probe_execution(
            c, self.objective, self.deliverables, execution_root=self.tmp
        )
        expected_path = os.path.join(self.tmp, "probe_out.py")
        self.assertTrue(os.path.exists(expected_path))

    def test_probe_populates_deliverables_dict(self):
        c = self._make_candidate(with_guardrails=True)
        result = self.adapter.probe_execution(c, self.objective, self.deliverables)
        self.assertIn("probe_out.py", result.deliverables)
        self.assertGreater(len(result.deliverables["probe_out.py"]), 0)

    def test_probe_fault_frames_populated_on_failure(self):
        c = self._make_candidate(with_guardrails=False)
        result = self.adapter.probe_execution(c, self.objective, self.deliverables)
        self.assertGreater(len(result.fault_frames), 0)

    def test_probe_no_fault_frames_on_success(self):
        c = self._make_candidate(with_guardrails=True)
        result = self.adapter.probe_execution(c, self.objective, self.deliverables)
        self.assertEqual(len(result.fault_frames), 0)

    def test_probe_multiple_deliverables(self):
        deliverables = [
            {"path": "a.py", "description": "File A"},
            {"path": "b.py", "description": "File B"},
        ]
        c = self._make_candidate(with_guardrails=True)
        result = self.adapter.probe_execution(c, self.objective, deliverables)
        self.assertIn("a.py", result.deliverables)
        self.assertIn("b.py", result.deliverables)

    def test_probe_stdout_set_on_success(self):
        c = self._make_candidate(with_guardrails=True)
        result = self.adapter.probe_execution(c, self.objective, self.deliverables)
        self.assertIn("[SIM]", result.stdout)
        self.assertEqual(result.stderr, "")

    def test_probe_stderr_set_on_failure(self):
        c = self._make_candidate(with_guardrails=False)
        result = self.adapter.probe_execution(c, self.objective, self.deliverables)
        self.assertIn("[SIM]", result.stderr)
        self.assertEqual(result.stdout, "")

    def test_probe_candidate_with_skills_succeeds(self):
        cfg = HarnessConfig(system_prompt="A", skills=["python-best-practices"])
        c = HarnessCandidate(harness=cfg)
        result = self.adapter.probe_execution(c, self.objective, self.deliverables)
        self.assertEqual(result.status, "success")


